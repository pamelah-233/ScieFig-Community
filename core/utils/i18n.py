def trf(key: str, **values: object) -> str:
    """Translate a UI template and interpolate runtime values."""
    return tr(key).format(**values)


_I18N_KEY_PROPERTIES = {
    "text": "i18nTextKey",
    "title": "i18nTitleKey",
    "toolTip": "i18nToolTipKey",
    "placeholder": "i18nPlaceholderKey",
}


def bind_i18n(widget, key: str, attribute: str = "text"):
    """Attach an explicit translation key to a persistent UI property."""
    if attribute not in _I18N_KEY_PROPERTIES:
        raise ValueError(f"Unsupported i18n attribute: {attribute}")

    legacy_key = widget.property("i18nKey")
    legacy_attribute = str(widget.property("i18nAttribute") or "text")
    legacy_property = _I18N_KEY_PROPERTIES.get(legacy_attribute)
    if isinstance(legacy_key, str) and legacy_property and not isinstance(widget.property(legacy_property), str):
        widget.setProperty(legacy_property, legacy_key)

    widget.setProperty(_I18N_KEY_PROPERTIES[attribute], key)
    if attribute == "text" or not isinstance(legacy_key, str):
        widget.setProperty("i18nKey", key)
        widget.setProperty("i18nAttribute", attribute)
    _set_i18n_attribute(widget, attribute, tr(key))
    return widget


def retranslate_bound_widgets(root) -> None:
    """Refresh widgets previously registered with :func:`bind_i18n`."""
